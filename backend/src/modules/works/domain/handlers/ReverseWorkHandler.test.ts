import { describe, it, expect, beforeAll, afterAll, beforeEach } from 'vitest';
import { ReverseWorkHandler } from './ReverseWorkHandler';
import { Work } from '../../../../models/Work';
import { InventoryItem } from '../../../../models/InventoryItem';
import { InventoryMovement } from '../../../../models/InventoryMovement';
import { Remnant } from '../../../../models/Remnant';
import { Unit } from '../../../../models/Unit';
import { Category } from '../../../../models/Category';
import { Subcategory } from '../../../../models/Subcategory';
import { connectTestDb, clearTestDb, closeTestDb } from '../../../../tests/helpers/testDb';
import mongoose from 'mongoose';

describe('ReverseWorkHandler', () => {
  const handler = new ReverseWorkHandler();
  let pipeItem: any;
  let unitPieces: any;
  let unitMeters: any;

  beforeAll(async () => {
    await connectTestDb();
  });

  afterAll(async () => {
    await closeTestDb();
  });

  beforeEach(async () => {
    await clearTestDb();

    unitPieces = await Unit.create({ name: 'Pieza', symbol: 'pz', allowsDecimals: false });
    unitMeters = await Unit.create({ name: 'Metro', symbol: 'm', allowsDecimals: true });

    const category = await Category.create({ name: 'Perfiles' });
    const subcategory = await Subcategory.create({ name: 'Tubos', category: category._id, unit: unitPieces._id });

    pipeItem = await InventoryItem.create({
      name: 'Tubo 6m',
      kind: 'material',
      category: category._id,
      subcategory: subcategory._id,
      unit: unitPieces._id,
      stock: 10,
      avgUnitCost: '60.00',
    });
  });

  it('throws an error if work is not found', async () => {
    const fakeId = new mongoose.Types.ObjectId().toString();
    const request: any = { targetId: fakeId };
    const ctx: any = { actorId: new mongoose.Types.ObjectId().toString(), role: 'admin' };

    await expect(handler.apply(request, {}, ctx, undefined)).rejects.toThrow('Obra no encontrada');
  });

  it('throws an error if work status is not approved', async () => {
    const pendingWork = await Work.create({
      clientName: 'Cliente X',
      performedAt: new Date(),
      status: 'pending_approval',
      createdBy: new mongoose.Types.ObjectId(),
    });

    const request: any = { targetId: pendingWork._id.toString() };
    const ctx: any = { actorId: new mongoose.Types.ObjectId().toString(), role: 'admin' };

    await expect(handler.apply(request, {}, ctx, undefined)).rejects.toThrow(
      'Solo se pueden revertir obras aprobadas'
    );
  });

  it('blocks reversal (rule P7) if a remnant generated by the work was already consumed', async () => {
    const remnantUsed = await Remnant.create({
      item: pipeItem._id,
      measure: 3.0,
      unit: unitMeters._id,
      costPerMeasureSnapshot: 10.0,
      status: 'used', // already consumed in another work!
      createdBy: new mongoose.Types.ObjectId(),
    });

    const work = await Work.create({
      clientName: 'Cliente Y',
      performedAt: new Date(),
      status: 'approved',
      createdBy: new mongoose.Types.ObjectId(),
      items: [
        {
          item: pipeItem._id,
          kind: 'material',
          mode: 'measure',
          source: 'whole_piece',
          measureUsed: 3.0,
          remnantsCreated: [remnantUsed._id],
        },
      ],
    });

    const request: any = { targetId: work._id.toString() };
    const ctx: any = { actorId: new mongoose.Types.ObjectId().toString(), role: 'admin' };

    await expect(handler.apply(request, {}, ctx, undefined)).rejects.toThrow(
      'Reversión bloqueada: El retazo generado por esta obra'
    );
  });

  it('successfully reverses work with pieces and restores stock', async () => {
    const work = await Work.create({
      clientName: 'Cliente Z',
      performedAt: new Date(),
      status: 'approved',
      createdBy: new mongoose.Types.ObjectId(),
      items: [
        {
          item: pipeItem._id,
          kind: 'material',
          mode: 'pieces',
          piecesConsumed: 2,
        },
      ],
    });

    // Current stock is 10. Reversing 2 pieces consumed should bring stock to 12.
    const request: any = {
      targetId: work._id.toString(),
      requestedBy: new mongoose.Types.ObjectId().toString(),
    };
    const ctx: any = { actorId: new mongoose.Types.ObjectId().toString(), role: 'admin' };

    const reversed = await handler.apply(request, {}, ctx, undefined);
    expect(reversed.status).toBe('rejected');

    const updatedItem = await InventoryItem.findById(pipeItem._id);
    expect(Number(updatedItem?.stock.toString())).toBe(12);

    const movement = await InventoryMovement.findOne({ type: 'work_reversal' });
    expect(movement).toBeDefined();
    expect(movement?.quantity?.toString()).toBe('2');
  });

  it('reverses work with measure cut from whole_piece and invalidates created remnant', async () => {
    const childRemnant = await Remnant.create({
      item: pipeItem._id,
      measure: 3.5,
      unit: unitMeters._id,
      costPerMeasureSnapshot: 10.0,
      status: 'available',
      createdBy: new mongoose.Types.ObjectId(),
    });

    const work = await Work.create({
      clientName: 'Cliente Cut Reversal',
      performedAt: new Date(),
      status: 'approved',
      createdBy: new mongoose.Types.ObjectId(),
      items: [
        {
          item: pipeItem._id,
          kind: 'material',
          mode: 'measure',
          source: 'whole_piece',
          piecesConsumed: 1,
          remnantsCreated: [childRemnant._id],
        },
      ],
    });

    const request: any = {
      targetId: work._id.toString(),
      requestedBy: new mongoose.Types.ObjectId().toString(),
    };
    const ctx: any = { actorId: new mongoose.Types.ObjectId().toString(), role: 'admin' };

    await handler.apply(request, {}, ctx, undefined);

    const updatedItem = await InventoryItem.findById(pipeItem._id);
    expect(Number(updatedItem?.stock.toString())).toBe(11); // 10 + 1

    const updatedRemnant = await Remnant.findById(childRemnant._id);
    expect(updatedRemnant?.status).toBe('discarded');
  });

  it('reverses work with measure cut from remnant and restores original remnant to available', async () => {
    const originalRemnant = await Remnant.create({
      item: pipeItem._id,
      measure: 5.0,
      unit: unitMeters._id,
      costPerMeasureSnapshot: 10.0,
      status: 'used',
      createdBy: new mongoose.Types.ObjectId(),
    });

    const childRemnant = await Remnant.create({
      item: pipeItem._id,
      measure: 2.0,
      unit: unitMeters._id,
      costPerMeasureSnapshot: 10.0,
      status: 'available',
      createdBy: new mongoose.Types.ObjectId(),
    });

    const work = await Work.create({
      clientName: 'Cliente Remnant Reversal',
      performedAt: new Date(),
      status: 'approved',
      createdBy: new mongoose.Types.ObjectId(),
      items: [
        {
          item: pipeItem._id,
          kind: 'material',
          mode: 'measure',
          source: 'remnant',
          remnant: originalRemnant._id,
          remnantsCreated: [childRemnant._id],
        },
      ],
    });

    const request: any = {
      targetId: work._id.toString(),
      requestedBy: new mongoose.Types.ObjectId().toString(),
    };
    const ctx: any = { actorId: new mongoose.Types.ObjectId().toString(), role: 'admin' };

    await handler.apply(request, {}, ctx, undefined);

    const restoredOriginal = await Remnant.findById(originalRemnant._id);
    expect(restoredOriginal?.status).toBe('available');
    expect(restoredOriginal?.usedInWork).toBeNull();

    const invalidatedChild = await Remnant.findById(childRemnant._id);
    expect(invalidatedChild?.status).toBe('discarded');
  });

  it('reverses work with legacy material and restores stock', async () => {
    const work = await Work.create({
      clientName: 'Cliente Legacy',
      performedAt: new Date(),
      status: 'approved',
      createdBy: new mongoose.Types.ObjectId(),
      items: [
        {
          item: pipeItem._id,
          kind: 'material',
          quantity: 5,
        },
      ],
    });

    const request: any = {
      targetId: work._id.toString(),
      requestedBy: new mongoose.Types.ObjectId().toString(),
    };
    const ctx: any = { actorId: new mongoose.Types.ObjectId().toString(), role: 'admin' };

    await handler.apply(request, {}, ctx, undefined);

    const updatedItem = await InventoryItem.findById(pipeItem._id);
    expect(Number(updatedItem?.stock.toString())).toBe(15); // 10 + 5
  });

  it('reverses work with tool item without altering item stock', async () => {
    const tool = await InventoryItem.create({
      name: 'Taladro Reversal',
      kind: 'tool',
      category: pipeItem.category,
      subcategory: pipeItem.subcategory,
      unit: unitMeters._id,
      stock: 4,
      avgUnitCost: '150',
    });

    const work = await Work.create({
      clientName: 'Cliente Reversal Tool',
      performedAt: new Date(),
      status: 'approved',
      createdBy: new mongoose.Types.ObjectId(),
      items: [
        {
          item: tool._id,
          kind: 'tool',
          quantity: 1,
        },
      ],
    });

    const request: any = {
      targetId: work._id.toString(),
      requestedBy: new mongoose.Types.ObjectId().toString(),
    };
    const ctx: any = { actorId: new mongoose.Types.ObjectId().toString(), role: 'admin' };

    await handler.apply(request, {}, ctx, undefined);

    const updatedTool = await InventoryItem.findById(tool._id);
    expect(Number(updatedTool?.stock.toString())).toBe(4);
  });
});
